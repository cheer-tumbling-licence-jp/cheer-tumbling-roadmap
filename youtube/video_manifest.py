def build_description(body: str) -> str:
    return body + FOOTER


def main():
    items = []
    drive_path = Path(DRIVE_DIR)

    for v in VIDEOS:
        path = drive_path / v["file"]
        item = {
            "file_path": str(path),
            "file_exists": path.exists(),
            "file_size_mb": round(path.stat().st_size / (1024 * 1024), 1) if path.exists() else None,
            "title": f'{v["title"]}｜チアタンブリングロードマップ',
            "description": build_description(v["body"]),
            "tags": COMMON_TAGS + v["tags"],
            "category_id": "17",  # Sports
            "privacy_status": "unlisted",  # 限定公開
            "made_for_kids": False,
            "language": "ja",
            "default_audio_language": "ja",
        }
        items.append(item)

    out_json = Path("/Users/don/cheer_tumbling_app/youtube/video_manifest.json")
    out_json.write_text(json.dumps(items, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"✅ video_manifest.json 出力: {len(items)} 件")

    # ファイル存在チェック
    missing = [it for it in items if not it["file_exists"]]
    if missing:
        print(f"⚠️ ファイルが見つからない: {len(missing)} 件")
        for it in missing:
            print(f"  - {it['file_path']}")
    else:
        print("✅ 全ファイル存在確認")

    # 監督確認用 Markdown
    md_lines = ["# 動画メタデータ レビュー\n", f"## アップロード対象：{len(items)} 件\n"]
    for i, it in enumerate(items, 1):
        size = f"{it['file_size_mb']} MB" if it['file_size_mb'] else "❌ ファイル無し"
        md_lines.append(f"### {i}. {it['title']} ({size})")
        md_lines.append(f"")
        md_lines.append(f"**説明文**：")
        md_lines.append(f"```")
        md_lines.append(it["description"])
        md_lines.append(f"```")
        md_lines.append(f"")
        md_lines.append(f"**タグ**：{', '.join(it['tags'])}")
        md_lines.append(f"")
        md_lines.append(f"**公開設定**：限定公開（URL を知っている人のみ閲覧可、検索結果非表示）")
        md_lines.append(f"")
        md_lines.append("---\n")

    md_lines.append("## 保留扱い\n")
    for h in HOLDOUT:
        md_lines.append(f"- **{h['file']}**")
        md_lines.append(f"  - 理由：{h['reason']}")
        md_lines.append("")

    out_md = Path("/Users/don/cheer_tumbling_app/youtube/video_review.md")
    out_md.write_text("\n".join(md_lines), encoding="utf-8")
    print(f"✅ video_review.md 出力（監督確認用）")


if __name__ == "__main__":
    main()
